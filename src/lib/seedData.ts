import { Trade } from './types';
import { calculateTradeFinancials } from './calculations';

function makeSeedTrade(
  id: string,
  trade_date: string,
  entry_time: string,
  exit_time: string,
  instrument: string,
  instrument_type: any,
  direction: 'Long' | 'Short',
  quantity: number,
  entry_price: number,
  exit_price: number,
  stop_loss: number,
  target: number,
  brokerage: number,
  charges: number,
  strategy: string,
  market_condition: any,
  timeframe: any,
  entry_reason: string,
  before_emotion: any,
  during_emotion: any,
  after_emotion: any,
  plan_followed: boolean,
  fomo: boolean,
  revenge_trading: boolean,
  overtrading: boolean,
  early_exit: boolean,
  mistake_tags: string[],
  what_went_well: string,
  what_went_wrong: string,
  learning: string,
  next_time: string
): Trade {
  const fin = calculateTradeFinancials({
    direction,
    quantity,
    entry_price,
    exit_price,
    stop_loss,
    target,
    brokerage,
    charges,
  });

  return {
    id,
    user_id: 'seed-user-demo',
    trade_date,
    entry_time,
    exit_time,
    instrument,
    instrument_type,
    direction,
    quantity,
    entry_price,
    exit_price,
    stop_loss,
    target,
    account_capital: 500000,
    risk_percent: 1,
    risk_amount: fin.planned_risk_amount,
    planned_rr: fin.planned_rr,
    actual_rr: fin.actual_rr,
    position_size_method: 'auto',
    gross_pnl: fin.gross_pnl,
    gross_pnl_percent: fin.gross_pnl_percent,
    brokerage: fin.brokerage,
    charges: fin.charges,
    net_pnl: fin.net_pnl,
    net_pnl_percent: fin.net_pnl_percent,
    r_multiple: fin.r_multiple,
    mae: direction === 'Long' ? entry_price - 12 : entry_price + 10,
    mfe: direction === 'Long' ? exit_price + 8 : exit_price - 7,
    strategy,
    custom_strategy: null,
    entry_reason,
    market_condition,
    timeframe,
    entry_screenshot_url: null,
    exit_screenshot_url: null,
    before_emotion,
    during_emotion,
    after_emotion,
    plan_followed,
    fomo,
    revenge_trading,
    overtrading,
    early_exit,
    psychology_notes: plan_followed ? 'Kept emotions in check, honored stop loss.' : 'Felt anxious when price fluctuated near open.',
    what_went_well,
    what_went_wrong,
    learning,
    next_time,
    mistake_tags,
    created_at: `${trade_date}T${entry_time}:00Z`,
    updated_at: `${trade_date}T${exit_time}:00Z`,
  };
}

